"""
Utility functions for the package.
"""


def add(a, b):
    """
    Add two numbers together.
    
    Args:
        a: First number
        b: Second number
        
    Returns:
        Sum of a and b
    """
    return a + b


def multiply(a, b):
    """
    Multiply two numbers together.
    
    Args:
        a: First number
        b: Second number
        
    Returns:
        Product of a and b
    """
    return a * b


def greet(name):
    """
    Greet a person by name.
    
    Args:
        name: Name of the person
        
    Returns:
        Greeting message
    """
    return f"Hello, {name}!"
